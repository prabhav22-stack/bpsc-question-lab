def research_topic_with_grounding(
    query: str,
    include_bihar_angle: bool = True,
    client_override: Any = None,
) -> Tuple[str, List[Dict[str, str]]]:
    """Research a syllabus topic using Google Search grounding where supported."""
    client = client_override or _get_client()
    model = get_gemini_model()

    bihar_inst = "Identify any specific Bihar angle or relevance." if include_bihar_angle else ""
    prompt = f"""Research the following civil services topic for BPSC / UPSC exam preparation:
Query: {query}

Instructions:
1. Provide an executive summary of key background and latest developments.
2. Extract high-yield facts (data, dates, constitutional articles, statutory bodies, committee recommendations).
3. {bihar_inst}
4. Link to relevant BPSC / UPSC General Studies syllabus topics.
"""

    citations: List[Dict[str, str]] = []
    try:
        # Enable Google Search grounding tool
        config = types.GenerateContentConfig(
            system_instruction=SYSTEM_SOURCE_RESEARCHER,
            tools=[types.Tool(google_search=types.GoogleSearch())],
            temperature=0.2,
        )
        response = client.models.generate_content(
            model=model,
            contents=prompt,
            config=config,
        )

        # Extract genuine grounding citations if returned
        if hasattr(response, "candidates") and response.candidates:
            cand = response.candidates[0]
            if hasattr(cand, "grounding_metadata") and cand.grounding_metadata:
                gm = cand.grounding_metadata
                if hasattr(gm, "grounding_chunks") and gm.grounding_chunks:
                    for chunk in gm.grounding_chunks:
                        if hasattr(chunk, "web") and chunk.web:
                            title = getattr(chunk.web, "title", "") or "Web Source"
                            uri = getattr(chunk.web, "uri", "") or ""
                            if uri:
                                citations.append({"title": title, "url": uri})

        text = response.text or "No synthesis generated."
        return text, citations
    except Exception:
        # Fallback to standard synthesis without search tool if search tool fails or is restricted
        try:
            fallback_config = types.GenerateContentConfig(
                system_instruction=SYSTEM_SOURCE_RESEARCHER,
                temperature=0.2,
            )
            fallback_resp = client.models.generate_content(
                model=model,
                contents=prompt,
                config=fallback_config,
            )
            return fallback_resp.text or "", []
        except Exception as exc:
            raise AIServiceError(f"Research synthesis failed: {exc}") from exc


def translate_hindi_question_to_english(
    question: str,
    option_a: str = "",
    option_b: str = "",
    option_c: str = "",
    option_d: str = "",
    explanation: str = "",
) -> Dict[str, str]:
    """Translate a Hindi question and its options into standard, academic English."""
    if not is_gemini_configured():
        raise AIServiceError("Gemini API is not configured.")
    client = _get_client()
    model = get_gemini_model()

    prompt = (
        "You are an expert bilingual examination translator for BPSC and UPSC Civil Services.\n"
        "Translate the following Hindi multiple-choice question and options into clear, standard, academic English.\n"
        "Maintain standard official terminology (e.g. translate 'मौलिक अधिकार' as 'Fundamental Rights', "
        "'राज्यपाल' as 'Governor', 'संसद' as 'Parliament', 'पंचायती राज' as 'Panchayati Raj', 'महाजनपद' as 'Mahajanapada').\n\n"
        f"Hindi Question: {question}\n"
        f"Option A: {option_a}\n"
        f"Option B: {option_b}\n"
        f"Option C: {option_c}\n"
        f"Option D: {option_d}\n"
        f"Explanation: {explanation}\n\n"
        "Return a JSON object with keys: 'question', 'option_a', 'option_b', 'option_c', 'option_d', 'explanation'."
    )

    try:
        response = client.models.generate_content(
            model=model,
            contents=[prompt],
            config=types.GenerateContentConfig(
                response_mime_type="application/json",
                temperature=0.1,
            ),
        )
        data = json.loads(response.text)
        return {
            "question": data.get("question", question),
            "option_a": data.get("option_a", option_a),
            "option_b": data.get("option_b", option_b),
            "option_c": data.get("option_c", option_c),
            "option_d": data.get("option_d", option_d),
            "explanation": data.get("explanation", explanation),
        }
    except Exception as exc:
        raise AIServiceError(f"Failed to translate Hindi question: {exc}") from exc

