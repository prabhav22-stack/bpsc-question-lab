class AIServiceError(Exception):
    """Raised when an AI operation fails gracefully."""
    pass


def _get_client() -> Any:
    """Return an authenticated genai.Client instance."""
    if not _HAS_GENAI:
        raise AIServiceError("The 'google-genai' library is not installed.")
    if not is_gemini_configured():
        raise AIServiceError(
            "Gemini API key is not configured. Please add your key to "
            "'.streamlit/secrets.toml' or '.env' as GEMINI_API_KEY."
        )
    key = get_gemini_api_key()
    return genai.Client(api_key=key)


def test_connection(client_override: Any = None) -> Dict[str, Any]:
    """Test the Gemini API connection securely on-demand.

    Returns a dict with success status, latency_ms, model, and sanitized message.
    Guarantees no raw API key is ever displayed, printed, or logged.
    """
    import time

    if not is_gemini_configured() and client_override is None:
        return {
            "success": False,
            "message": "Gemini API key is not configured. Please set GEMINI_API_KEY in '.streamlit/secrets.toml' or '.env'.",
            "latency_ms": 0.0,
            "model": get_gemini_model(),
        }

    model = get_gemini_model()
    t0 = time.time()
    try:
        client = client_override or _get_client()
        response = client.models.generate_content(
            model=model,
            contents="Respond with only the single word: OK",
        )
        latency = round((time.time() - t0) * 1000, 1)
        return {
            "success": True,
            "message": f"Connection successful! Model '{model}' responded in {latency} ms.",
            "latency_ms": latency,
            "model": model,
        }
    except Exception as exc:
        latency = round((time.time() - t0) * 1000, 1)
        err_str = str(exc)
        key = get_gemini_api_key()
        if key and key in err_str:
            err_str = err_str.replace(key, "••••••••")
        return {
            "success": False,
            "message": f"Connection failed ({type(exc).__name__}): {err_str}",
            "latency_ms": latency,
            "model": model,
        }


def generate_question_set(
    exam: str,
    subject: str,
    topic: str,
    subtopic: str = "",
    count: int = 5,
    difficulty: str = "Medium",
    question_type: str = "Standard MCQ",
    focus: str = "PYQ-inspired practice",
    notes_or_context: str = "",
    client_override: Any = None,
    exemplars: Optional[List[Dict[str, Any]]] = None,
) -> GeneratedQuestionSet:
    """Generate a validated set of practice questions calibrated against genuine BPSC Prelims PYQs."""
    client = client_override or _get_client()
    model = get_gemini_model()

    # Retrieve authentic official PYQs as few-shot exemplars if not provided
    if exemplars is None:
        try:
            import db
            exemplars = db.retrieve_pyq_exemplars(
                subject=subject,
                topic=topic,
                exam=exam,
                limit=5,
            )
        except Exception:
            exemplars = []

    prompt = build_question_generation_prompt(
        exam=exam,
        subject=subject,
        topic=topic,
        subtopic=subtopic,
        count=count,
        difficulty=difficulty,
        question_type=question_type,
        focus=focus,
        notes_or_context=notes_or_context,
        exemplars=exemplars,
    )

    try:
        config = types.GenerateContentConfig(
            system_instruction=SYSTEM_QUESTION_STUDIO,
            response_mime_type="application/json",
            response_schema=GeneratedQuestionSet,
            temperature=0.3,
        )
        response = client.models.generate_content(
            model=model,
            contents=prompt,
            config=config,
        )
        if response.text:
            data = json.loads(response.text)
            validated = GeneratedQuestionSet.model_validate(data)
            # Ensure subject/topic propagate if model left defaults
            for q in validated.questions:
                if not q.subject or q.subject == "Other":
                    q.subject = subject
                if not q.topic or q.topic == "General":
                    q.topic = topic
                if subtopic and not q.subtopic:
                    q.subtopic = subtopic
            validated.retrieved_exemplars = exemplars or []
            return validated
        raise AIServiceError("Gemini returned an empty response.")
    except Exception as exc:
        raise AIServiceError(f"Question generation failed: {exc}") from exc


