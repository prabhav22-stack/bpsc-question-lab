"""AI Service layer for BPSC Question Lab v1.0.

Provides official google-genai SDK integration with Gemini for:
- Structured question generation (AI Question Studio)
- Conceptual learning & explanations (AI Study Tutor)
- Mistake diagnosis ("Explain my mistake")
- Performance diagnostics (AI Performance Coach)
- Source-aware research with web search grounding & citations

Safely handles unconfigured keys, rate limits, and network errors.
Deterministic numbers and test records are never generated by AI.
"""

