def tutor_query(
    mode: str,
    user_query: str = "",
    question_text: str = "",
    options: Optional[Dict[str, str]] = None,
    correct_option: str = "",
    selected_option: str = "",
    explanation: str = "",
    chat_history: Optional[List[Dict[str, str]]] = None,
    client_override: Any = None,
) -> str:
    """Query the AI Study Tutor for conceptual guidance."""
    client = client_override or _get_client()
    model = get_gemini_model()

    prompt = build_tutor_prompt(
        mode=mode,
        question_text=question_text,
        options=options or {},
        correct_option=correct_option,
        student_selected=selected_option,
        explanation=explanation,
        user_query=user_query,
    )

    contents: List[Any] = []
    if chat_history:
        for turn in chat_history[-6:]:  # Keep recent context bounded
            role = "user" if turn.get("role") == "user" else "model"
            contents.append(types.Content(role=role, parts=[types.Part.from_text(text=turn.get("content", ""))]))

    contents.append(types.Content(role="user", parts=[types.Part.from_text(text=prompt)]))

    try:
        config = types.GenerateContentConfig(
            system_instruction=SYSTEM_AI_TUTOR,
            temperature=0.3,
        )
        response = client.models.generate_content(
            model=model,
            contents=contents,
            config=config,
        )
        return response.text or "No response generated."
    except Exception as exc:
        raise AIServiceError(f"Tutor response failed: {exc}") from exc


